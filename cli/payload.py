"""build the tree that lands in a pi's home directory.

the staging directory is laid out exactly as it should appear under $HOME, so
what gets pushed is what you can see in `pi sync -n`.

a colour, a glyph or a service name lives in exactly one place and everything
that needs it in another format is rendered from there. the generated files all
say so in their first line, because finding one on a box and editing it is
otherwise a reasonable thing to try.
"""

from __future__ import annotations

import io
import shutil
import tarfile
from dataclasses import dataclass
from pathlib import Path

from . import ROOT
from .manifest import App, Host, apps_on, resolvers

# service configs are root-owned system files, so they land here inert and are
# only installed when the host's install script runs
SERVICES_HOME = Path(".local/share/pi-services")


@dataclass
class Payload:
    host: Host
    root: Path

    @property
    def files(self) -> list[Path]:
        return sorted(p for p in self.root.rglob("*") if p.is_file())

    @property
    def names(self) -> list[str]:
        return [str(p.relative_to(self.root)) for p in self.files]

    @property
    def size(self) -> int:
        return sum(p.stat().st_size for p in self.files)

    def tar(self) -> bytes:
        buf = io.BytesIO()
        with tarfile.open(fileobj=buf, mode="w") as tar:
            for path in sorted(self.root.rglob("*")):
                tar.add(path, arcname=str(path.relative_to(self.root)))
        return buf.getvalue()


# ── generated files ─────────────────────────────────────────────────────────


def rgb(hex_colour: str) -> str:
    """#9b6bc9 -> the sgr escape bin/services prints"""
    h = hex_colour.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    return f"\\033[38;2;{r};{g};{b}m"


def starship(host: Host) -> str:
    """starship has no include directive, so the palette is concatenated on"""
    c = host.colors
    return f"""
# generated by pi from hosts/{host.name}/host.toml
[palettes.moon]
accent = "{c["accent"]}"
bright = "{c["bright"]}"
alt = "{c["alt"]}"
dim = "{c["dim"]}"

[character]
success_symbol = "[{host.glyph} ❯](accent)"
error_symbol = "[{host.glyph} ❯](alt)"
vicmd_symbol = "[{host.glyph} ❮](dim)"
"""


def host_zsh(host: Host) -> str:
    c = host.colors
    return f"""# generated by pi from hosts/{host.name}/host.toml, edits here are overwritten
MOON_NAME="{host.name}"
MOON_GLYPH="{host.glyph}"
MOON_ACCENT="{c["accent"]}"
MOON_BRIGHT="{c["bright"]}"
MOON_ALT="{c["alt"]}"
MOON_DIM="{c["dim"]}"
"""


def host_env(host: Host) -> str:
    """what bin/services reads: this host's palette and its full service list"""
    c = host.colors
    listing = "\n".join(
        [*host.services, *(f"{a.label}|{a.name}|{a.name}" for a in apps_on(host.name))]
    )
    return f"""# generated by pi from apps.toml and hosts/{host.name}/host.toml
PI_HOST={host.name}
PI_GLYPH='{host.glyph}'
PI_ACCENT='{rgb(c["accent"])}'
PI_BRIGHT='{rgb(c["bright"])}'
PI_DIM='{rgb(c["dim"])}'
PI_SERVICES='
{listing}
'
"""


def app_units(app: App) -> list[Path]:
    """an app's openrc unit and conf.d, if it ships them"""
    return [
        p for p in (ROOT / app.name / f"{app.name}.{s}" for s in ("initd", "confd")) if p.is_file()
    ]


# ── staging ─────────────────────────────────────────────────────────────────


def _copy_into(src: Path, dst: Path, mode: int | None = None) -> None:
    dst.mkdir(parents=True, exist_ok=True)
    for f in sorted(src.iterdir()):
        if f.is_file():
            shutil.copy2(f, dst / f.name)
            if mode is not None:
                (dst / f.name).chmod(mode)


def build(host: Host, staging: Path) -> Payload:
    staging.mkdir(parents=True, exist_ok=True)

    # the login shell
    zsh = staging / ".config" / "zsh"
    shutil.copy2(ROOT / "shell" / "zshrc", staging / ".zshrc")
    _copy_into(ROOT / "shell" / "zsh", zsh)
    (zsh / "host.zsh").write_text(host_zsh(host))

    prompt = (ROOT / "shell" / "starship.toml").read_text()
    (staging / ".config" / "starship.toml").write_text(prompt + starship(host))

    pi_conf = staging / ".config" / "pi"
    pi_conf.mkdir(parents=True, exist_ok=True)
    (pi_conf / "host.env").write_text(host_env(host))

    _copy_into(ROOT / "bin", staging / ".local" / "bin", mode=0o755)

    if not host.installable:
        return Payload(host, staging)

    services = staging / SERVICES_HOME / host.name
    services.mkdir(parents=True, exist_ok=True)
    for f in sorted(host.dir.iterdir()):
        if f.is_file() and f.name not in ("host.toml", "README.md"):
            shutil.copy2(f, services / f.name)
            if f.name == "install":
                (services / f.name).chmod(0o755)

    # one adguard seed for every resolver on the fleet, so leda and thebe
    # cannot drift apart the way two copies of it did
    if host.name in resolvers():
        shutil.copy2(ROOT / "hosts" / "adguardhome.yaml", services / "adguardhome.yaml")

    # each app contributes its own openrc unit and conf.d, so adding an app is
    # adding a directory rather than editing this file
    for app in apps_on(host.name):
        for unit in app_units(app):
            shutil.copy2(unit, services / unit.name)

    wanted = {name for a in apps_on(host.name) for name in a.artefacts}
    build_dir = ROOT / "build"
    if build_dir.is_dir():
        for f in sorted(build_dir.iterdir()):
            if f.is_file() and f.name in wanted:
                shutil.copy2(f, services / f.name)
                (services / f.name).chmod(0o755)

    return Payload(host, staging)
